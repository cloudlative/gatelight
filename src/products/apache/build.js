'use strict';
/**
 * Config Builder, Apache httpd 2.4: normalised spec (src/build/spec.js) -> configuration files.
 *
 * Layouts (spec.options.layout, or build(spec, { layout })):
 *   'debian'     (default) conf-available/gatelight.conf (server-wide settings + balancers) and sites-available/<site>.conf;
 *                modules / sites are enabled with a2enmod / a2enconf / a2ensite (listed in notes), no LoadModule lines.
 *   'rhel'       conf.d/00-gatelight.conf + conf.d/<site>.conf (read by IncludeOptional conf.d/*.conf); modules come
 *                from /etc/httpd/conf.modules.d (mod_ssl, mod_md, mod_http2 are separate packages, see notes).
 *   'standalone' one complete httpd.conf with ServerRoot, Listen and LoadModule lines (upstream build / httpd image).
 *
 * Every directive follows https://httpd.apache.org/docs/2.4/ and is gated on the target version (spec.version).
 */
const { normalizeSpec } = require('../../build/spec');
const V = require('../../validate/version');
const kb = require('../../kb/apache.json');

const CIPHERS = 'ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384:ECDHE-ECDSA-CHACHA20-POLY1305:ECDHE-RSA-CHACHA20-POLY1305';
const LB = { roundrobin: 'byrequests', leastconn: 'bybusyness', iphash: 'byrequests', random: 'byrequests' };
const DOC = 'https://httpd.apache.org/docs/2.4/';
const LAYOUTS = {
  debian: { conf: 'conf-available/gatelight.conf', site: (n) => `sites-available/${n}.conf`, logDir: '${APACHE_LOG_DIR}', htpasswd: '/etc/apache2', caBundle: '/etc/ssl/certs/ca-certificates.crt', defaultListen: ['80', '443'], test: 'apache2ctl configtest', reload: 'systemctl reload apache2' },
  rhel: { conf: 'conf.d/00-gatelight.conf', site: (n) => `conf.d/${n}.conf`, logDir: 'logs', htpasswd: '/etc/httpd', caBundle: '/etc/pki/tls/certs/ca-bundle.crt', defaultListen: ['80', '443'], test: 'httpd -t', reload: 'systemctl reload httpd' },
  standalone: { conf: 'httpd.conf', site: null, logDir: 'logs', htpasswd: '/usr/local/apache2/conf', caBundle: '/etc/ssl/certs/ca-certificates.crt', defaultListen: [], test: 'apachectl configtest', reload: 'apachectl graceful' },
};

const q = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const escRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function build(input, opts = {}) {
  const spec = normalizeSpec(input);
  const rawLayout = String(opts.layout || (input && input.options && input.options.layout) || 'debian').toLowerCase();
  const layout = rawLayout === 'upstream' ? 'standalone' : LAYOUTS[rawLayout] ? rawLayout : 'debian';
  const Lx = LAYOUTS[layout];
  const notes = []; const unsupported = [];
  const parsedV = V.parse(spec.version);
  const target = parsedV && parsedV[0] === 2 && parsedV[1] === 4 ? parsedV.join('.') : kb.latest;
  if (spec.version && target !== spec.version) notes.push(`"${spec.version}" is not an httpd 2.4.x version; the configuration targets ${target}.`);
  const gte = (v) => V.gte(target, v);
  const mods = new Set(['proxy', 'proxy_http', 'proxy_balancer', 'slotmem_shm', 'headers', 'alias', 'authz_core', 'authz_host']);
  const pools = new Map(spec.pools.map((p) => [p.name, p]));
  const usedPools = new Set(spec.sites.flatMap((s) => [...s.routes.map((r) => r.pool), ...(s.defaultPool ? [s.defaultPool] : [])]));
  const tlsSites = spec.sites.filter((s) => s.tls.mode !== 'none');
  const acmeSites = tlsSites.filter((s) => s.tls.mode === 'acme');
  const httpsPoolUse = new Set(spec.sites.flatMap((s) => [...s.routes.map((r) => r.pool), s.defaultPool].filter((p) => p && pools.get(p).scheme === 'https').map(() => s.name)));
  const wsLegacy = spec.sites.some((s) => s.websocket) && !gte('2.4.47');

  // ------------------------------------------------------------------ server-wide
  const g = [];
  const listen = new Set();
  for (const s of spec.sites) { listen.add(String(s.http.port)); if (s.https) listen.add(`${s.https.port}${layout === 'standalone' ? '' : ''}`); }
  if (spec.options.statusPage.enabled) listen.add(String(spec.options.statusPage.port));
  const extraListen = [...listen].filter((p) => !Lx.defaultListen.includes(p)).sort((a, b) => a - b);
  g.push('# Generated by GateLight Config Builder for Apache httpd ' + target + ` (${layout} layout).`);
  g.push(`# Documentation: ${DOC}`);
  g.push('');
  if (layout === 'standalone') {
    g.push('ServerRoot "/usr/local/apache2"');
    for (const p of [...listen].sort((a, b) => a - b)) g.push(`Listen ${p}`);
    g.push('@@LOADMODULE@@');
    g.push('User daemon', 'Group daemon', 'ServerAdmin webmaster@localhost', '');
    g.push('ErrorLog logs/error_log', 'LogLevel warn', 'DocumentRoot "/usr/local/apache2/htdocs"', '');
    g.push('<Directory />', '    AllowOverride None', '    Require all denied', '</Directory>', '');
    g.push('<Directory "/usr/local/apache2/htdocs">', '    Options FollowSymLinks', '    AllowOverride None', '    Require all granted', '</Directory>', '');
    g.push('TypesConfig conf/mime.types', '');
  } else if (extraListen.length) {
    g.push(`# Ports beyond the ${Lx.defaultListen.join('/')} that ${layout === 'debian' ? 'ports.conf' : 'httpd.conf / ssl.conf'} already listen on`);
    for (const p of extraListen) g.push(`Listen ${p}`);
    g.push('');
  }
  g.push('# Hardening', 'ServerTokens Prod', 'ServerSignature Off', 'TraceEnable Off', `Timeout ${spec.options.clientTimeout}`, '');
  // MPM sizing (event MPM: MaxRequestWorkers <= ServerLimit * ThreadsPerChild)
  const maxConn = spec.options.maxConnections;
  let threads = 25; let serverLimit = Math.max(1, Math.ceil(maxConn / threads));
  if (spec.options.workers !== 'auto') { serverLimit = spec.options.workers; threads = Math.min(64, Math.max(1, Math.ceil(maxConn / serverLimit))); }
  const mrw = serverLimit * threads;
  g.push('<IfModule mpm_event_module>', `    ServerLimit ${serverLimit}`, `    ThreadsPerChild ${threads}`, `    MaxRequestWorkers ${mrw}`, '</IfModule>', '');
  if (mrw !== maxConn) notes.push(`MaxRequestWorkers is ${mrw} (ServerLimit ${serverLimit} × ThreadsPerChild ${threads}), the nearest value to ${maxConn} the event MPM accepts.`);
  if (serverLimit > 16) notes.push(`ServerLimit ${serverLimit} is above the default of 16; httpd needs a full restart (not a graceful reload) for it to take effect.`);
  // logging
  if (spec.options.accessLog) {
    if (spec.options.logFormat === 'json') g.push('LogFormat "{ \\"time\\":\\"%{%Y-%m-%dT%H:%M:%S%z}t\\", \\"remote_addr\\":\\"%a\\", \\"vhost\\":\\"%v\\", \\"host\\":\\"%{Host}i\\", \\"request\\":\\"%r\\", \\"status\\":%>s, \\"bytes\\":%B, \\"duration_us\\":%D, \\"balancer\\":\\"%{BALANCER_NAME}e\\", \\"worker\\":\\"%{BALANCER_WORKER_NAME}e\\", \\"user_agent\\":\\"%{User-Agent}i\\" }" gatelight_json');
    else g.push('# vhost_combined plus the response time in microseconds (%D) and the balancer member that answered', 'LogFormat "%v:%p %h %l %u %t \\"%r\\" %>s %O \\"%{Referer}i\\" \\"%{User-Agent}i\\" %D \\"%{BALANCER_WORKER_NAME}e\\"" gatelight_combined');
    g.push('');
  }
  // TLS
  if (tlsSites.length) {
    mods.add('ssl'); mods.add('socache_shmcb');
    let proto = '-all +TLSv1.2';
    if (gte('2.4.36')) proto = tlsSites.every((s) => s.tls.minVersion === '1.3') ? '-all +TLSv1.3' : '-all +TLSv1.2 +TLSv1.3';
    else if (tlsSites.some((s) => s.tls.minVersion === '1.3')) unsupported.push(`TLS 1.3 only: httpd ${target} is older than 2.4.36, which added TLSv1.3 to SSLProtocol; TLS 1.2 is used instead (${DOC}mod/mod_ssl.html#sslprotocol).`);
    if (tlsSites.some((s) => s.tls.minVersion === '1.3') && !tlsSites.every((s) => s.tls.minVersion === '1.3') && gte('2.4.36')) notes.push('SSLProtocol is a server-wide setting here; sites asking for TLS 1.3 only get TLS 1.2 + 1.3 because other sites need 1.2.');
    g.push('# TLS (Mozilla intermediate profile)', `SSLProtocol ${proto}`, `SSLCipherSuite ${CIPHERS}`, 'SSLHonorCipherOrder off');
    if (gte('2.4.11')) g.push('SSLSessionTickets off');
    if (layout === 'standalone') g.push('SSLSessionCache "shmcb:logs/ssl_scache(512000)"', 'SSLSessionCacheTimeout 300');
    if (gte('2.4.17')) { g.push('Protocols h2 http/1.1'); mods.add('http2'); }
    g.push('');
  }
  if (acmeSites.length) {
    if (!gte('2.4.30')) {
      unsupported.push(`ACME (Let's Encrypt): mod_md ships with httpd 2.4.30 and later; ${target} is older. Use certificate files from an external ACME client (certbot) instead (${DOC}mod/mod_md.html).`);
    } else {
      mods.add('md'); mods.add('watchdog');
      g.push('# Certificates from Let\'s Encrypt through mod_md', 'MDCertificateAgreement accepted');
      const email = acmeSites.map((s) => s.tls.email).find(Boolean);
      if (email) { if (gte('2.4.42')) g.push(`MDContactEmail ${email}`); else g.push(`ServerAdmin ${email}`); }
      else notes.push('No ACME contact e-mail was given; mod_md uses ServerAdmin for the account.');
      for (const s of acmeSites) g.push(`MDomain ${s.hosts.join(' ')}`);
      g.push('');
      notes.push('mod_md requests the certificates in the background after the first start and needs one more graceful reload to use them (watch `/.httpd/certificate-status` or the error log).');
    }
  }
  g.push('# Reverse proxy', 'ProxyRequests Off', `ProxyTimeout ${Math.max(...spec.pools.map((p) => p.timeouts.server), 60)}`, '');

  // ------------------------------------------------------------------ balancers
  const hcOk = gte('2.4.21');
  const stickyRoute = (p, i) => `${p.name.replace(/[^A-Za-z0-9_-]/g, '')}${i + 1}`;
  for (const p of spec.pools) {
    if (!usedPools.has(p.name)) notes.push(`Pool "${p.name}" is not used by any site; it is defined anyway.`);
    const lb = LB[p.balance];
    mods.add(`lbmethod_${lb}`);
    if (p.balance === 'iphash') notes.push(`Pool "${p.name}": httpd has no source-IP hash; clients are pinned with the ROUTEID cookie (sticky session) instead (${DOC}mod/mod_proxy_balancer.html#stickyness_implementation).`);
    if (p.balance === 'random') notes.push(`Pool "${p.name}": httpd has no random scheduler; byrequests (weighted round robin) is used (${DOC}mod/mod_proxy_balancer.html#scheduler).`);
    const sticky = p.sticky || p.balance === 'iphash';
    const hc = p.healthCheck;
    if (hc && hcOk) { mods.add('proxy_hcheck'); mods.add('watchdog'); }
    if (hc && !hcOk) unsupported.push(`Pool "${p.name}" active health checks: mod_proxy_hcheck needs httpd 2.4.21+; ${target} only marks members failed after real errors (retry=).`);
    g.push(`<Proxy ${q(`balancer://${p.name}`)}>`);
    p.servers.forEach((sv, i) => {
      const parts = [`BalancerMember ${q(`${p.scheme}://${sv.address}`)}`];
      if (sticky) parts.push(`route=${stickyRoute(p, i)}`);
      if (sv.weight != null && sv.weight !== 1) parts.push(`loadfactor=${Math.max(1, Math.min(100, sv.weight))}`);
      if (sv.backup) parts.push('status=+H');
      parts.push(`connectiontimeout=${p.timeouts.connect}`, `timeout=${p.timeouts.server}`);
      if (hc && hcOk) parts.push('hcmethod=GET', `hcuri=${hc.path}`, `hcinterval=${hc.interval}`, `hcpasses=${hc.rise}`, `hcfails=${hc.fall}`);
      g.push(`    ${parts.join(' ')}`);
    });
    g.push(`    ProxySet lbmethod=${lb}${sticky ? ' stickysession=ROUTEID' : ''}`);
    g.push('</Proxy>', '');
    if (p.servers.some((s) => s.weight === 0)) notes.push(`Pool "${p.name}": weight 0 is not possible in httpd (loadfactor 1..100); those members get loadfactor=1.`);
    if (hc && hcOk && hc.timeout) notes.push(`Pool "${p.name}": mod_proxy_hcheck has no separate check timeout; checks use the member's connectiontimeout (${p.timeouts.connect} s) / timeout.`);
  }
  if (wsLegacy) {
    mods.add('proxy_wstunnel'); mods.add('rewrite');
    for (const name of new Set(spec.sites.filter((s) => s.websocket).flatMap((s) => [...s.routes.map((r) => r.pool), s.defaultPool].filter(Boolean)))) {
      const p = pools.get(name);
      g.push(`# WebSocket twin of "${name}" for mod_proxy_wstunnel (httpd before 2.4.47)`, `<Proxy ${q(`balancer://${name}-ws`)}>`);
      p.servers.forEach((sv) => g.push(`    BalancerMember ${q(`${p.scheme === 'https' ? 'wss' : 'ws'}://${sv.address}`)}${sv.backup ? ' status=+H' : ''}`));
      g.push(`    ProxySet lbmethod=${LB[p.balance]}`, '</Proxy>', '');
      mods.add(`lbmethod_${LB[p.balance]}`);
    }
  }

  // ------------------------------------------------------------------ status page
  if (spec.options.statusPage.enabled) {
    mods.add('status');
    const allow = spec.options.statusPage.allow.length ? spec.options.statusPage.allow : ['127.0.0.1'];
    g.push('# Monitoring: mod_status (?auto for machines) and the balancer manager, only from the allowed addresses', 'ExtendedStatus On');
    g.push(`<VirtualHost *:${spec.options.statusPage.port}>`, '    ServerName status.localhost');
    for (const [loc, h] of [['/server-status', 'server-status'], ['/balancer-manager', 'balancer-manager']]) g.push(`    <Location ${q(loc)}>`, `        SetHandler ${h}`, `        Require ip ${allow.join(' ')}`, '    </Location>');
    g.push('    RedirectMatch 404 "^/(?!server-status|balancer-manager)"', '</VirtualHost>', '');
    if (layout === 'debian') notes.push('Debian\'s mods-enabled/status.conf also serves /server-status on every site, restricted to `Require local`; GateLight can read it there or on the dedicated status port.');
  }

  // ------------------------------------------------------------------ sites
  const siteFiles = [];
  const stickyCookie = (poolNames) => [...new Set(poolNames)].some((n) => pools.get(n) && (pools.get(n).sticky || pools.get(n).balance === 'iphash'));
  for (const s of spec.sites) {
    const out = [];
    const hosts = s.hosts;
    const primary = hosts[0] || null;
    const names = () => { const l = []; if (primary) l.push(`    ServerName ${primary}`); if (hosts.length > 1) l.push(`    ServerAlias ${hosts.slice(1).join(' ')}`); return l; };
    const usedHere = [...s.routes.map((r) => r.pool), ...(s.defaultPool ? [s.defaultPool] : [])];
    const logLines = spec.options.accessLog ? [`    ErrorLog ${Lx.logDir}/${s.name}_error${layout === 'debian' ? '.log' : '_log'}`, `    CustomLog ${Lx.logDir}/${s.name}_access${layout === 'debian' ? '.log' : '_log'} ${spec.options.logFormat === 'json' ? 'gatelight_json' : 'gatelight_combined'}`] : [];
    const httpsPortSuffix = s.https && s.https.port !== 443 ? `:${s.https.port}` : '';
    const body = (scheme) => {
      const b = [];
      if (s.redirectTo) {
        b.push(`    Redirect permanent "/" ${q(s.redirectTo.endsWith('/') ? s.redirectTo : `${s.redirectTo}/`)}`);
        return b;
      }
      b.push('    ProxyPreserveHost On', `    RequestHeader set X-Forwarded-Proto "${scheme}"`);
      if (usedHere.some((n) => pools.get(n).scheme === 'https')) {
        mods.add('ssl');
        b.push('    SSLProxyEngine on');
        const verify = usedHere.filter((n) => pools.get(n).scheme === 'https').every((n) => pools.get(n).verifyTls);
        if (verify) b.push('    SSLProxyVerify require', `    SSLProxyCACertificateFile ${Lx.caBundle}`, '    SSLProxyCheckPeerName on');
        else b.push('    SSLProxyVerify none', '    SSLProxyCheckPeerName off', '    SSLProxyCheckPeerExpire off');
      }
      if (stickyCookie(usedHere)) {
        b.push('    Header add Set-Cookie "ROUTEID=.%{BALANCER_WORKER_ROUTE}e; path=/" env=BALANCER_ROUTE_CHANGED');
        if (new Set(usedHere.filter((n) => pools.get(n).sticky || pools.get(n).balance === 'iphash')).size > 1 && scheme === 'https') notes.push(`Site "${s.name}" uses several sticky pools; they share the ROUTEID cookie, so a client alternating between them is re-balanced each time.`);
      }
      if (scheme === 'https' && s.tls.hsts) b.push('    Header always set Strict-Transport-Security "max-age=63072000"');
      if (s.securityHeaders) b.push('    Header always set X-Content-Type-Options "nosniff"', '    Header always set X-Frame-Options "SAMEORIGIN"', '    Header always set Referrer-Policy "strict-origin-when-cross-origin"');
      if (s.compression) { mods.add('deflate'); mods.add('filter'); b.push('    AddOutputFilterByType DEFLATE text/html text/plain text/css text/xml text/javascript application/javascript application/json application/xml image/svg+xml'); }
      if (s.maxBodyMb != null) b.push(`    LimitRequestBody ${s.maxBodyMb * 1048576}`);
      if (s.basicAuth) {
        mods.add('auth_basic'); mods.add('authn_file'); mods.add('authn_core'); mods.add('authz_user');
        const file = `${Lx.htpasswd}/.htpasswd-${s.name}`;
        b.push('    <Location "/">', '        AuthType Basic', `        AuthName ${q(s.basicAuth.realm)}`, '        AuthBasicProvider file', `        AuthUserFile ${q(file)}`, '        Require valid-user', '    </Location>');
        if (scheme === 'https' || !s.https) notes.push(`Site "${s.name}": create ${file} (readable by the httpd user only) with these lines (bcrypt hashes as given, the format \`htpasswd -B\` writes):\n${s.basicAuth.users.map((u) => `${u.user}:${u.hash}`).join('\n')}`);
      }
      const ws = s.websocket && gte('2.4.47') ? ' upgrade=websocket' : '';
      if (s.websocket && wsLegacy) b.push('    RewriteEngine On');
      const rules = [...s.routes, ...(s.defaultPool ? [{ path: '/', match: 'prefix', pool: s.defaultPool, stripPrefix: false, rewriteTo: null, isDefault: true }] : [])];
      for (const r of rules) {
        const bal = `balancer://${r.pool}`;
        const p = r.path;
        let pass; let rev; let wsRule;
        if (r.match === 'exact') {
          const to = r.rewriteTo || (r.stripPrefix ? '/' : p);
          pass = `    ProxyPassMatch ${q(`^${escRe(p)}$`)} ${q(`${bal}${to}`)}${ws}`;
          rev = `    ProxyPassReverse ${q(p)} ${q(`${bal}${to}`)}`;
          wsRule = [`^${escRe(p)}$`, `${to}`];
        } else if (p.endsWith('/')) {
          const to = r.rewriteTo ? (r.rewriteTo.endsWith('/') ? r.rewriteTo : `${r.rewriteTo}/`) : r.stripPrefix ? '/' : p;
          pass = `    ProxyPass ${q(p)} ${q(`${bal}${to}`)}${ws}`;
          rev = `    ProxyPassReverse ${q(p)} ${q(`${bal}${to}`)}`;
          wsRule = [`^${escRe(p)}(.*)$`, `${to}$1`];
        } else {
          // "/api" must match /api and /api/... but not /apix: a regex keeps the segment boundary
          const to = r.rewriteTo ? r.rewriteTo.replace(/\/$/, '') : r.stripPrefix ? '' : p;
          pass = `    ProxyPassMatch ${q(`^${escRe(p)}(/.*)?$`)} ${q(`${bal}${to}$1`)}${ws}`;
          rev = `    ProxyPassReverse ${q(`${p}/`)} ${q(`${bal}${to}/`)}`;
          wsRule = [`^${escRe(p)}(/.*)?$`, `${to}$1`];
        }
        if (s.websocket && wsLegacy) b.push('    RewriteCond %{HTTP:Upgrade} =websocket [NC]', `    RewriteRule ${q(wsRule[0])} ${q(`balancer://${r.pool}-ws${wsRule[1] || '/'}`)} [P,L]`);
        b.push(pass, rev);
      }
      if (!s.defaultPool) b.push('    # no default pool: everything not routed above answers 404', '    RedirectMatch 404 "^/"');
      return b;
    };
    if (s.https) {
      // HTTP side: redirect (or the same content when redirectHttp is off)
      out.push(`<VirtualHost *:${s.http.port}>`, ...names());
      if (s.tls.redirectHttp && !s.redirectTo) {
        if (hosts.length === 1) out.push(`    Redirect permanent "/" "https://${primary}${httpsPortSuffix}/"`);
        else { mods.add('rewrite'); out.push('    RewriteEngine On', `    RewriteRule "^/(.*)$" "https://%{${httpsPortSuffix ? 'SERVER_NAME' : 'HTTP_HOST'}}${httpsPortSuffix}/$1" [R=301,L]`); }
      } else out.push(...body('http'));
      out.push(...logLines, '</VirtualHost>', '');
      out.push(`<VirtualHost *:${s.https.port}>`, ...names(), '    SSLEngine on');
      if (s.tls.mode === 'files') out.push(`    SSLCertificateFile ${q(s.tls.cert)}`, `    SSLCertificateKeyFile ${q(s.tls.key)}`);
      else if (!gte('2.4.30')) out.push('    # mod_md is not available on this version: point these at certificates from your ACME client', `    SSLCertificateFile "/etc/letsencrypt/live/${primary}/fullchain.pem"`, `    SSLCertificateKeyFile "/etc/letsencrypt/live/${primary}/privkey.pem"`);
      out.push(...body('https'), ...logLines, '</VirtualHost>', '');
    } else {
      out.push(`<VirtualHost *:${s.http.port}>`, ...names(), ...body('http'), ...logLines, '</VirtualHost>', '');
    }
    if (!hosts.length) notes.push(`Site "${s.name}" has no host names: httpd answers unknown names with the FIRST virtual host of each address:port, so keep this site's file first (e.g. name it 000-${s.name}.conf).`);
    if (s.rateLimit) unsupported.push(`Site "${s.name}" rate limit (${s.rateLimit.rps} r/s, burst ${s.rateLimit.burst}): httpd has no request-rate limiter in its standard modules. mod_ratelimit only limits bandwidth per response (RATE_LIMIT in KiB/s, ${DOC}mod/mod_ratelimit.html). Use a third-party module (mod_qos, mod_evasive) or a limiter in front of httpd.`);
    siteFiles.push({ site: s, content: out.join('\n') });
  }

  // ------------------------------------------------------------------ assemble
  const modList = [...mods].sort();
  const MOD_ID = (m) => `${m}_module`;
  const loadLines = ['# Modules', 'LoadModule mpm_event_module modules/mod_mpm_event.so', 'LoadModule unixd_module modules/mod_unixd.so', 'LoadModule log_config_module modules/mod_log_config.so', 'LoadModule mime_module modules/mod_mime.so', 'LoadModule dir_module modules/mod_dir.so', 'LoadModule setenvif_module modules/mod_setenvif.so',
    ...modList.map((m) => `LoadModule ${MOD_ID(m)} modules/mod_${m}.so`), ''];
  const files = [];
  if (layout === 'standalone') {
    const content = [...g.join('\n').replace('@@LOADMODULE@@', loadLines.join('\n')).split('\n'), ...siteFiles.map((f) => `# ---- site ${f.site.name}\n${f.content}`)].join('\n');
    files.push({ name: 'httpd.conf', content: `${content.replace(/\n{3,}/g, '\n\n').trimEnd()}\n` });
  } else {
    files.push({ name: Lx.conf, content: `${g.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n` });
    for (const f of siteFiles) files.push({ name: Lx.site(f.site.hosts.length ? f.site.name : `000-${f.site.name}`), content: `# Site "${f.site.name}" — generated by GateLight Config Builder\n\n${f.content.trimEnd()}\n` });
  }
  const a2mods = modList;
  if (layout === 'debian') {
    notes.unshift(`Enable and apply (Debian / Ubuntu):\n  a2enmod ${a2mods.join(' ')}\n  a2enconf gatelight\n  a2ensite ${siteFiles.map((f) => (f.site.hosts.length ? f.site.name : `000-${f.site.name}`)).join(' ')}\n  ${Lx.test} && ${Lx.reload}`);
    if (mods.has('md')) notes.push('mod_md is packaged with apache2 on Debian / Ubuntu (a2enmod md).');
  } else if (layout === 'rhel') {
    const pkgs = ['mod_ssl', 'mod_md', 'mod_http2'].filter((p) => mods.has(p.replace(/^mod_/, '').replace('http2', 'http2')));
    notes.unshift(`Apply (RHEL / Fedora): ${pkgs.length ? `dnf install ${pkgs.join(' ')} (these packages add their LoadModule lines to /etc/httpd/conf.modules.d); ` : ''}copy the files to /etc/httpd/, then ${Lx.test} && ${Lx.reload}. All other modules used (${modList.filter((m) => !['ssl', 'md', 'http2'].includes(m)).map((m) => `mod_${m}`).join(', ')}) are loaded by the default conf.modules.d (00-base.conf, 00-proxy.conf).`);
    notes.push('SELinux: allow httpd to connect to the backends with `setsebool -P httpd_can_network_connect 1`, and for non-standard ports `semanage port -a -t http_port_t -p tcp <port>`.');
  } else {
    notes.unshift(`Apply: copy httpd.conf to /usr/local/apache2/conf/ (official httpd image: /usr/local/apache2/conf/httpd.conf), then ${Lx.test} && ${Lx.reload}.`);
  }
  return { files, notes, unsupported, layout, target, modules: modList };
}

