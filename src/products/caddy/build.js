'use strict';
/**
 * Config Builder: normalised spec (src/build/spec.js) -> a complete Caddyfile for the target Caddy version.
 *
 * Each pool becomes a snippet `(pool_<name>)` holding its reverse_proxy, imported by the routes that use it. Version
 * facts come from the knowledge base (src/kb/caddy.json): basic_auth (2.8; basicauth before), raw bcrypt hashes in
 * basic auth (2.6; base64-encoded before), weighted_round_robin / client_ip_hash (2.7), health_passes / health_fails (2.8),
 * request_body (2.3), servers timeouts (2.3), metrics directive (2.2).
 */
const { normalizeSpec } = require('../../build/spec');
const { kb, V, target: resolveTarget, available } = require('./kb');

const I = '\t';
const has = (T, kind, name, sub) => {
  const e = kind === 'directive' ? kb.directives[name] : kind === 'option' ? kb.options[name] : kind === 'policy' ? kb.lbPolicies[name] : null;
  if (!e || !available(e, T)) return false;
  if (!sub) return true;
  return Boolean(e.sub && e.sub[sub] && available(e.sub[sub], T));
};
const q = (s) => (/[\s"{}#]/.test(s) || s === '' ? `"${String(s).replace(/"/g, '\\"')}"` : s);

function build(input) {
  const spec = normalizeSpec(input);
  const tgt = resolveTarget(spec.version);
  const T = tgt.version;
  const notes = []; const unsupported = [];
  if (tgt.note) notes.push(tgt.note);
  const out = [];
  const line = (depth, text) => out.push(text ? `${I.repeat(depth)}${text}` : '');

  // ---------------------------------------------------------------- global options
  const tlsSites = spec.sites.filter((s) => s.tls.mode !== 'none');
  const emails = [...new Set(tlsSites.filter((s) => s.tls.mode === 'acme' && s.tls.email).map((s) => s.tls.email))];
  const httpPorts = [...new Set(tlsSites.map((s) => s.http.port))];
  const httpsPorts = [...new Set(tlsSites.map((s) => s.https.port))];
  const noRedirect = tlsSites.length && tlsSites.every((s) => !s.tls.redirectHttp);
  const someNoRedirect = tlsSites.some((s) => !s.tls.redirectHttp) && !noRedirect;
  out.push(`# Caddyfile generated by GateLight Config Builder for Caddy ${T}`);
  out.push('# Validate with: caddy validate --config Caddyfile --adapter caddyfile');
  out.push('{');
  if (emails.length === 1) line(1, `email ${emails[0]}`);
  line(1, 'admin localhost:2019');
  if (httpPorts.length === 1 && httpPorts[0] !== 80) line(1, `http_port ${httpPorts[0]}`);
  if (httpsPorts.length === 1 && httpsPorts[0] !== 443) line(1, `https_port ${httpsPorts[0]}`);
  if (httpPorts.length > 1 || httpsPorts.length > 1) notes.push('Caddy has one HTTP and one HTTPS port for automatic HTTPS; sites with other ports carry them in their address, but their automatic redirects use the global ports.');
  if (noRedirect) { line(1, 'auto_https disable_redirects'); notes.push('Automatic HTTP->HTTPS redirects are turned off globally (auto_https disable_redirects), as no TLS site asked for them.'); }
  if (someNoRedirect) notes.push('Caddy redirects HTTP to HTTPS automatically for every TLS site; it can only be turned off globally (auto_https disable_redirects), so sites that asked for no redirect still get one.');
  if (has(T, 'option', 'servers', 'timeouts')) {
    line(1, 'servers {');
    line(2, 'timeouts {');
    line(3, `read_body ${Math.max(10, Math.min(spec.options.clientTimeout, 300))}s`);
    line(3, 'read_header 10s');
    line(3, `idle ${Math.max(spec.options.clientTimeout, 30)}s`);
    line(2, '}');
    if (spec.options.statusPage.enabled && has(T, 'option', 'servers', 'metrics') && !has(T, 'option', 'metrics')) line(2, 'metrics');
    line(1, '}');
  } else notes.push(`Caddy ${T} has no servers { timeouts } option (2.3+): client timeouts use Go defaults.`);
  if (spec.options.statusPage.enabled && has(T, 'option', 'metrics')) line(1, 'metrics');
  out.push('}');
  out.push('');
  if (spec.options.maxConnections) unsupported.push(`Maximum connections (${spec.options.maxConnections}): Caddy has no global connection limit; use OS limits (ulimit -n / LimitNOFILE).`);
  if (spec.options.workers !== 'auto') notes.push('Worker processes do not apply: Caddy is one Go process that uses all CPU cores (GOMAXPROCS).');

  // ---------------------------------------------------------------- pools as snippets
  const used = new Set(spec.sites.flatMap((s) => [s.defaultPool, ...s.routes.map((r) => r.pool)]).filter(Boolean));
  for (const p of spec.pools.filter((x) => used.has(x.name))) {
    out.push(`(pool_${p.name}) {`);
    const primaries = p.servers.filter((s) => !s.backup); const backups = p.servers.filter((s) => s.backup);
    const ordered = [...primaries, ...backups];
    line(1, `reverse_proxy ${ordered.map((s) => s.address).join(' ')} {`);
    let policy = { roundrobin: 'round_robin', leastconn: 'least_conn', iphash: has(T, 'policy', 'client_ip_hash') ? 'client_ip_hash' : 'ip_hash', random: 'random' }[p.balance];
    const weighted = ordered.some((s) => s.weight != null && s.weight !== 1);
    if (p.sticky) { policy = 'cookie lb'; if (p.balance !== 'random') notes.push(`Pool "${p.name}": sticky sessions use lb_policy cookie; the first request of a client is placed randomly (Caddy's cookie policy falls back to random), so "${p.balance}" is not used.`); }
    if (backups.length) {
      unsupported.push(`Pool "${p.name}": backup servers (${backups.map((b) => b.address).join(', ')}) — Caddy has no backup role. They are listed last as normal upstreams${p.sticky ? '' : '; to use them only when the others are down, switch to "lb_policy first" (always the first available upstream, no balancing)'}.`);
    }
    if (weighted && !p.sticky) {
      if (has(T, 'policy', 'weighted_round_robin') && p.balance === 'roundrobin') policy = `weighted_round_robin ${ordered.map((s) => (s.weight == null ? 1 : s.weight)).join(' ')}`;
      else unsupported.push(`Pool "${p.name}": server weights need lb_policy weighted_round_robin (Caddy 2.7+, round robin only)${has(T, 'policy', 'weighted_round_robin') ? ` and cannot be combined with ${p.balance}` : `; Caddy ${T} has no weighted policy`}.`);
    }
    if (policy === 'client_ip_hash') notes.push(`Pool "${p.name}": client_ip_hash uses the real client IP only behind proxies listed in servers { trusted_proxies ... }; add your load balancer ranges there if Caddy is not the edge.`);
    if (p.balance === 'iphash' && policy === 'ip_hash') notes.push(`Pool "${p.name}": ip_hash hashes the immediate peer address (client_ip_hash, which honours trusted_proxies, needs Caddy 2.7).`);
    line(2, `lb_policy ${policy}`);
    if (ordered.length > 1) line(2, 'lb_try_duration 5s');
    if (p.healthCheck) {
      line(2, `health_uri ${p.healthCheck.path}`);
      line(2, `health_interval ${p.healthCheck.interval}s`);
      line(2, `health_timeout ${p.healthCheck.timeout}s`);
      if (has(T, 'directive', 'reverse_proxy', 'health_passes')) { line(2, `health_passes ${p.healthCheck.rise}`); line(2, `health_fails ${p.healthCheck.fall}`); } else notes.push(`Pool "${p.name}": rise/fall counts need Caddy 2.8 (health_passes / health_fails); one probe decides on ${T}.`);
      line(2, 'fail_duration 30s');
    }
    line(2, 'transport http {');
    line(3, `dial_timeout ${p.timeouts.connect}s`);
    line(3, `response_header_timeout ${p.timeouts.server}s`);
    if (p.scheme === 'https') {
      line(3, 'tls');
      if (!p.verifyTls) { line(3, '# certificate verification disabled on request; prefer tls_trust_pool / tls_trusted_ca_certs'); line(3, 'tls_insecure_skip_verify'); notes.push(`Pool "${p.name}": upstream certificates are not verified (tls_insecure_skip_verify).`); }
    }
    line(2, '}');
    line(1, '}');
    out.push('}');
    out.push('');
  }

  // ---------------------------------------------------------------- sites
  const basicName = has(T, 'directive', 'basic_auth') ? 'basic_auth' : 'basicauth';
  const rawHashes = V.gte(T, '2.6.0');
  for (const s of spec.sites) {
    const tls = s.tls.mode;
    const addrs = [];
    if (tls === 'none') {
      if (s.hosts.length) s.hosts.forEach((h) => addrs.push(`http://${h}${s.http.port !== 80 ? `:${s.http.port}` : ''}`));
      else addrs.push(`:${s.http.port}`);
    } else if (s.hosts.length) s.hosts.forEach((h) => addrs.push(`${h}${s.https.port !== 443 ? `:${s.https.port}` : ''}`));
    else addrs.push(`:${s.https.port}`);
    out.push(`# site ${s.name}`);
    out.push(`${addrs.join(', ')} {`);
    if (tls === 'files' || (tls === 'acme' && (emails.length > 1 && s.tls.email)) || (tls !== 'none' && s.tls.minVersion === '1.3')) {
      const head = tls === 'files' ? `tls ${q(s.tls.cert)} ${q(s.tls.key)}` : tls === 'acme' && emails.length > 1 && s.tls.email ? `tls ${s.tls.email}` : 'tls';
      if (s.tls.minVersion === '1.3') { line(1, `${head} {`); line(2, 'protocols tls1.3'); line(1, '}'); } else line(1, head);
    }
    if (tls === 'acme' && !s.tls.email && !emails.length) notes.push(`Site "${s.name}": no ACME e-mail given; Caddy still obtains certificates, but you will not get expiry warnings from the CA.`);
    if (tls === 'files') notes.push(`Site "${s.name}": certificates from files are not renewed by Caddy.`);
    if (tls === 'none' && s.hosts.length) notes.push(`Site "${s.name}": http:// opts out of Automatic HTTPS.`);
    if (s.securityHeaders || s.tls.hsts) {
      line(1, 'header {');
      if (s.tls.hsts && tls !== 'none') line(2, 'Strict-Transport-Security "max-age=31536000"');
      if (s.securityHeaders) { line(2, 'X-Content-Type-Options "nosniff"'); line(2, 'Referrer-Policy "strict-origin-when-cross-origin"'); line(2, 'X-Frame-Options "SAMEORIGIN"'); line(2, '-Server'); }
      line(1, '}');
    }
    if (s.compression) line(1, 'encode zstd gzip');
    if (spec.options.accessLog) {
      line(1, 'log {');
      line(2, `output file /var/log/caddy/${s.name}.access.log`);
      line(2, 'format json');
      line(1, '}');
    }
    if (s.maxBodyMb != null) {
      if (has(T, 'directive', 'request_body')) { line(1, 'request_body {'); line(2, `max_size ${s.maxBodyMb}MB`); line(1, '}'); } else unsupported.push(`Site "${s.name}": request body limit needs Caddy 2.3 (request_body).`);
    }
    if (s.basicAuth) {
      line(1, `${basicName} bcrypt ${q(s.basicAuth.realm)} {`);
      for (const u of s.basicAuth.users) line(2, `${u.user} ${rawHashes ? u.hash : Buffer.from(u.hash).toString('base64')}`);
      line(1, '}');
      if (!rawHashes) notes.push(`Site "${s.name}": Caddy ${T} expects base64-encoded bcrypt hashes; they were encoded for you.`);
    }
    if (s.rateLimit) unsupported.push(`Site "${s.name}": rate limiting (${s.rateLimit.rps} r/s, burst ${s.rateLimit.burst}) is not built into Caddy. Build Caddy with the github.com/mholt/caddy-ratelimit plugin (xcaddy) and add a rate_limit block with "order rate_limit before basic_auth".`);
    if (s.websocket) notes.push(`Site "${s.name}": WebSockets work through reverse_proxy without extra configuration (Upgrade is passed through; stream_close_delay can keep them open across config reloads).`);
    if (s.redirectTo) {
      line(1, `redir ${s.redirectTo.replace(/\/$/, '')}{uri} 301`);
    } else {
      for (const r of s.routes) {
        const m = r.match === 'exact' ? r.path : r.path.endsWith('/') ? `${r.path}*` : `${r.path}*`;
        // handle_path strips the prefix before anything inside runs; a rewrite inside it then adds the new prefix
        // (a sibling `uri strip_prefix` would run AFTER `rewrite`: rewrite comes first in Caddy's directive order)
        const strip = r.match === 'prefix' && (r.stripPrefix || r.rewriteTo);
        line(1, `${strip ? 'handle_path' : 'handle'} ${m} {`);
        if (r.rewriteTo) {
          if (r.match === 'exact') line(2, `rewrite * ${r.rewriteTo}?{query}`);
          else line(2, `rewrite * ${r.rewriteTo.replace(/\/$/, '')}{uri}`);
        }
        line(2, `import pool_${r.pool}`);
        line(1, '}');
      }
      line(1, 'handle {');
      if (s.defaultPool) line(2, `import pool_${s.defaultPool}`);
      else line(2, 'respond "Not Found" 404');
      line(1, '}');
    }
    out.push('}');
    out.push('');
  }

  // ---------------------------------------------------------------- status page
  if (spec.options.statusPage.enabled) {
    const sp = spec.options.statusPage;
    if (has(T, 'directive', 'metrics')) {
      out.push(`# Prometheus metrics, only for ${sp.allow.join(', ') || 'nobody'}`);
      out.push(`:${sp.port} {`);
      line(1, `@denied not remote_ip ${sp.allow.length ? sp.allow.join(' ') : '127.0.0.1'}`);
      line(1, 'abort @denied');
      line(1, 'metrics /metrics');
      out.push('}');
      out.push('');
      notes.push(`Status: Prometheus metrics on :${sp.port}/metrics; GateLight reads upstream health from the admin API (statsUrl http://127.0.0.1:2019), which stays on localhost.`);
    } else unsupported.push(`Status page: the metrics directive needs Caddy 2.2.`);
  }
  if (spec.options.logFormat !== 'json' && spec.options.accessLog) notes.push('Access logs are JSON: Caddy has no built-in combined/CLF format (the transform-encoder plugin can write one). GateLight reads Caddy JSON logs directly.');
  return { files: [{ name: 'Caddyfile', content: `${out.join('\n').replace(/\n{3,}/g, '\n\n').replace(/\n+$/, '')}\n` }], notes: [...new Set(notes)], unsupported: [...new Set(unsupported)] };
}

module.exports = { build };
